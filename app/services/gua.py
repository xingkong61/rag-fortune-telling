def relation(self_wx: str, other_wx: str) -> str:
    """体（我）对用（彼）的五行关系：比和 / 我生 / 生我 / 我克 / 克我。"""
    if self_wx == other_wx:
        return "比和"
    if _SHENG.get(self_wx) == other_wx:
        return "我生"
    if _SHENG.get(other_wx) == self_wx:
        return "生我"
    if _KE.get(self_wx) == other_wx:
        return "我克"
    return "克我"


