def lines6(up: str, down: str) -> list[int]:
    """上下卦 → 六爻（自下而上）。"""
    return list(GUA_LINES[down]) + list(GUA_LINES[up])


def gua_of_lines(lines: list[int]) -> tuple[str, str]:
    """六爻（自下而上）→ (上卦, 下卦)。"""
    return LINES_TO_GUA[tuple(lines[3:])], LINES_TO_GUA[tuple(lines[:3])]