def classify_question(text: str) -> dict:
    """按关键词给问事归类，返回类别、梅花占类名、六爻参考用神。"""
    q = text or ""
    for name, keys, meihua_zhan, yongshen in _CATEGORIES:
        if any(k in q for k in keys):
            return {"category": name, "meihua_zhan": meihua_zhan, "yongshen": yongshen}
    return {"category": "综合", "meihua_zhan": "占卜总诀", "yongshen": "以世爻为主，兼看动爻与用神"}


